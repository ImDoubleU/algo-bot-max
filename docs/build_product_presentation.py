def write_narration() -> None:
    NARRATION_OUTPUT.write_text(
        json.dumps(NARRATION, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    lines = [
        "# Сценарий видео Algo MAX",
        "",
        "Этот файл содержит готовый текст озвучки. Один раздел соответствует одному слайду презентации.",
        "",
    ]
    total_words = 0
    for index, item in enumerate(NARRATION, start=1):
        words = len(item["text"].split())
        total_words += words
        lines.extend(
            [
                f"## {index}. {item['title']}",
                "",
                item["text"],
                "",
            ]
        )
    estimated_minutes = total_words / 125
    lines.extend(
        [
            "## Параметры",
            "",
            f"- Слайдов: {len(NARRATION)}",
            f"- Слов: {total_words}",
            f"- Расчетная длительность: {estimated_minutes:.1f} мин.",
            "- Формат: 16:9, 1280×720, 24 кадра/с.",
            "",
        ]
    )
    SCRIPT_OUTPUT.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    presentation = build_presentation()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    presentation.save(OUTPUT)
    write_narration()
    print(f"Created {OUTPUT} ({len(presentation.slides)} slides)")
    print(f"Created {SCRIPT_OUTPUT}")
    print(f"Created {NARRATION_OUTPUT}")


if __name__ == "__main__":
    main()
