const helpFaqState = {
  category: "all",
  query: "",
  initialized: false,
  renderKey: "",
};

function normalizeHelpText(value) {
  return String(value || "")
    .toLocaleLowerCase("ru-RU")
    .replaceAll("ё", "е")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .replace(/(?:qr|куар|кьюар)\s*код/gu, "qr код")
    .replace(/(^|\s)ас(?=\s|$)/g, "$1ac")
    .trim();
}

function currentHelpRole() {
  if (["student", "parent"].includes(state.role)) return state.role;
  const staffRole = primaryStaffRole();
  if (staffRole === "superadmin") return "superadmin";
  if (staffRole === "partner_director") return "director";
  if (staffRole === "curator") return "curator";
  if (staffRole === "teacher") return "teacher";
  return "admin";
}

function helpAudience() {
  const role = currentHelpRole();
  return ["parent", "student"].includes(role) ? role : "staff";
}

function helpItemVisible(item) {
  return helpAudience() === "staff" || item.audiences?.includes(helpAudience());
}

function helpVisibleCategories() {
  const eligible = HELP_FAQ_ITEMS.filter(helpItemVisible);
  return HELP_FAQ_CATEGORIES.filter((category) => category.id === "all"
    || eligible.some((item) => item.category === category.id)).map((category, index) => ({
    ...category, label: category.id === "all" ? category.label : category.label.replace(/^\d+\.\s*/, `${index}. `),
  }));
}

function renderHelpCategoryFilters() {
  const root = qs("#helpCategoryFilters");
  const categories = helpVisibleCategories();
  const key = categories.map((category) => category.id).join(",");
  if (root.dataset.renderKey === key) return;
  root.dataset.renderKey = key;
  if (!categories.some((category) => category.id === helpFaqState.category)) helpFaqState.category = "all";
  root.innerHTML = categories.map((category) => `<button class="help-category-button" type="button"
    aria-pressed="false" data-help-category="${escapeHtml(category.id)}" title="Перейти к теме «${escapeHtml(category.label)}»">
    <i data-lucide="${escapeHtml(category.icon)}" aria-hidden="true"></i><span>${escapeHtml(category.label)}</span></button>`).join("");
}

function helpItemSearchText(item) {
  return normalizeHelpText([
    HELP_FAQ_CATEGORIES.find((category) => category.id === item.category)?.label || "",
    item.question,
    item.answer,
    item.steps.join(" "),
    item.note,
    item.support,
    item.keywords,
    item.roles.map((role) => HELP_ROLE_LABELS[role] || role).join(" "),
    item.images.map((image) => `${image.alt || ""} ${image.caption || ""}`).join(" "),
  ].join(" "));
}

function helpAudienceLabel(item) {
  if (!item.roles.length) return "";
  return item.roles
    .map((role) => HELP_ROLE_LABELS[role] || role)
    .join(", ");
}

function helpImagesMarkup(images) {
  if (!images.length) return "";
  return `
    <div class="help-faq-images">
      ${images.map((image) => `
        <figure class="help-faq-figure">
          <a
            class="help-faq-image-link"
            href="${escapeHtml(image.src)}"
            target="_blank"
            rel="noopener noreferrer"
            aria-label="Открыть скриншот крупнее"
          >
            <img
              src="${escapeHtml(image.src)}"
              alt="${escapeHtml(image.alt || "")}"
              loading="lazy"
              decoding="async"
            />
          </a>
          ${image.caption ? `<figcaption>${escapeHtml(image.caption)}</figcaption>` : ""}
        </figure>
      `).join("")}
    </div>
  `;
}

function helpAnswerMarkup(item) {
  return `
    <div class="help-faq-answer">
      <p>${escapeHtml(item.answer)}</p>
      ${item.video ? `<div class="help-faq-video" data-help-video-question="${escapeHtml(item.question)}"></div>` : ""}
      ${item.steps.length ? `<ol>${item.steps.map((step) => `<li>${escapeHtml(step)}</li>`).join("")}</ol>` : ""}
      ${item.video ? "" : helpImagesMarkup(item.images)}
      ${item.note ? `<p class="help-faq-note">${escapeHtml(item.note)}</p>` : ""}
      ${item.support ? `<div class="help-faq-support"><p>${escapeHtml(item.support)}</p><button type="button" class="secondary-action" data-help-support="${escapeHtml(item.question)}"><i data-lucide="message-circle" aria-hidden="true"></i>Сообщить о проблеме</button></div>` : ""}
    </div>
  `;
}

function initializeHelpFaq() {
  if (helpFaqState.initialized) return;
  const search = qs("#helpSearchInput");
  const clearButton = qs("#clearHelpSearchButton");
  const filters = qs("#helpCategoryFilters");
  const empty = qs("#helpEmptyState");
  if (!search || !clearButton || !filters || !empty) return;
  renderHelpCategoryFilters();

  search.addEventListener("input", () => {
    helpFaqState.query = search.value;
    helpFaqState.renderKey = "";
    renderHelpFaq();
  });
  clearButton.addEventListener("click", () => {
    helpFaqState.query = "";
    search.value = "";
    helpFaqState.renderKey = "";
    renderHelpFaq();
    search.focus();
  });
  filters.addEventListener("click", (event) => {
    const button = event.target.closest("[data-help-category]");
    if (!button) return;
    helpFaqState.category = button.dataset.helpCategory || "all";
    if (helpFaqState.query) {
      helpFaqState.query = "";
      helpFaqState.renderKey = "";
      renderHelpFaq();
    }
    filters.querySelectorAll("[data-help-category]").forEach((item) => {
      const selected = item === button;
      item.classList.toggle("is-active", selected);
      item.setAttribute("aria-pressed", String(selected));
    });
    const destination = helpFaqState.category === "all"
      ? qs("#helpFaqContent")
      : document.getElementById(`help-topic-${helpFaqState.category}`);
    destination?.scrollIntoView({ behavior: matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth", block: "start" });
  });
  empty.addEventListener("click", (event) => {
    if (!event.target.closest("[data-reset-help-search]")) return;
    helpFaqState.query = "";
    helpFaqState.category = "all";
    search.value = "";
    helpFaqState.renderKey = "";
    renderHelpFaq();
    search.focus();
  });
  helpFaqState.initialized = true;
  qs("#helpFaqContent")?.addEventListener("click", (event) => {
    if (event.target.closest("[data-help-back-top]")) {
      qs(".help-toolbar")?.scrollIntoView({behavior: "auto", block: "start"});
      search.focus({preventScroll: true});
    }
  });
}

function renderHelpFaq() {
  initializeHelpFaq();
  if (!helpFaqState.initialized) return;

  const content = qs("#helpFaqContent");
  const filters = qs("#helpCategoryFilters");
  const empty = qs("#helpEmptyState");
  const search = qs("#helpSearchInput");
  const clearButton = qs("#clearHelpSearchButton");
  if (!content || !filters || !empty || !search || !clearButton) return;
  renderHelpCategoryFilters();
  renderHelpGuides();

  const query = normalizeHelpText(helpFaqState.query);
  const role = currentHelpRole();
  const renderKey = `${helpFaqState.category}|${query}|${role}`;
  if (helpFaqState.renderKey === renderKey) return;
  helpFaqState.renderKey = renderKey;

  if (search.value !== helpFaqState.query) search.value = helpFaqState.query;
  clearButton.hidden = !helpFaqState.query;

  filters.querySelectorAll("[data-help-category]").forEach((button) => {
    const selected = helpFaqState.category === button.dataset.helpCategory;
    button.classList.toggle("is-active", selected);
    button.setAttribute("aria-pressed", String(selected));
  });

  const queryWords = query.split(" ").filter(Boolean);
  const visibleItems = HELP_FAQ_ITEMS.filter(helpItemVisible)
    .filter((item) => {
      const searchText = helpItemSearchText(item);
      return queryWords.every((word) => searchText.includes(word));
    });
  qs("#helpSearchStatus").textContent = query ? `Найдено ответов: ${visibleItems.length}` : "";

  empty.hidden = visibleItems.length > 0;
  content.hidden = visibleItems.length === 0;

  const categoryOrder = helpVisibleCategories().filter((category) => category.id !== "all");
  content.querySelectorAll("video").forEach((video) => video.pause());
  content.innerHTML = categoryOrder.map((category) => {
    const categoryItems = visibleItems.filter((item) => item.category === category.id);
    if (!categoryItems.length) return "";
    return `
      <section class="help-topic" aria-labelledby="help-topic-${escapeHtml(category.id)}">
        <header class="help-topic-heading">
          <span aria-hidden="true"><i data-lucide="${escapeHtml(category.icon)}"></i></span>
          <h2 id="help-topic-${escapeHtml(category.id)}">${escapeHtml(category.label)}</h2>
          <button type="button" class="icon-button help-back-top" data-help-back-top title="К темам и поиску" aria-label="К темам и поиску"><i data-lucide="arrow-up" aria-hidden="true"></i></button>
        </header>
        <div class="help-accordion">
          ${categoryItems.map((item) => `
            <details class="help-faq-item" data-help-question="${escapeHtml(item.question)}">
              <summary class="help-faq-question">
                <span>${escapeHtml(item.question)}</span>
                <i data-lucide="chevron-down" aria-hidden="true"></i>
              </summary>
              ${helpAnswerMarkup(item)}
            </details>
          `).join("")}
        </div>
      </section>
    `;
  }).join("");

  content.querySelectorAll(".help-faq-item").forEach((item) => {
    item.addEventListener("toggle", () => {
      if (!item.open) { item.querySelector("video")?.pause(); return; }
      const answer = HELP_FAQ_ITEMS.find((entry) => entry.question === item.dataset.helpQuestion);
      if (!answer || !helpItemVisible(answer)) { item.open = false; return; }
      pauseHelpVideos();
      mountHelpFaqVideo(item, answer);
      content.querySelectorAll(".help-faq-item[open]").forEach((openedItem) => {
        if (openedItem !== item) openedItem.open = false;
      });
      refreshIcons();
    });
  });
  refreshIcons();
}
