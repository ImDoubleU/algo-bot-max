function helpFaq(category, question, answer, options = {}) {
  const roles = options.roles || [];
  const familyRoles = roles.filter((role) => ["parent", "student"].includes(role));
  const staffCategory = ["staff", "messages", "feedback", "management"].includes(category);
  const inferredAudiences = staffCategory || (roles.length && !familyRoles.length)
    ? ["staff"]
    : familyRoles.length ? familyRoles : ["parent", "student"];
  return Object.freeze({
    category,
    question,
    answer,
    steps: options.steps || [],
    note: options.note || "",
    roles,
    audiences: options.audiences || inferredAudiences,
    outcome: options.outcome || "",
    support: options.support || "",
    video: options.video !== false && (options.video === true || (options.steps || []).length > 0),
    keywords: options.keywords || "",
    images: options.images || [],
  });
}

