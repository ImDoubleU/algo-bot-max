from app.bot.backend_client import BackendApiError


def format_backend_error(exc: BackendApiError) -> str:
    messages = {
        "invitation_invalid": (
            "Ссылка повреждена или больше не действует. Попросите "
            "преподавателя открыть новый QR-код или школу отправить новое "
            "письмо."
        ),
        "invitation_legacy": (
            "Эта ссылка больше не используется. Попросите преподавателя открыть новый QR-код."
        ),
        "school_not_found": (
            "Не удалось найти школу для этой ссылки. Попросите школу отправить новую ссылку."
        ),
        "student_not_found": (
            "Профиль ученика не найден. Попросите преподавателя проверить ученика в списке группы."
        ),
        "student_access_closed": (
            "Доступ ученика закрыт. Обратитесь к преподавателю, чтобы проверить профиль."
        ),
        "parent_link_inactive": (
            "Подключение родителя сейчас неактивно. Попросите родителя открыть письмо "
            "школы и перейти по персональной ссылке."
        ),
        "account_role_conflict": (
            "Этот аккаунт MAX уже используется с другой ролью. Откройте "
            "ссылку в аккаунте нужного человека или обратитесь в поддержку."
        ),
        "student_already_bound": (
            "Этот аккаунт MAX уже привязан к другому ученику. Откройте QR-код "
            "в аккаунте ребёнка или попросите школу проверить привязку."
        ),
        "student_qr_required": (
            "Ученику нужен личный QR-код. Попросите преподавателя открыть "
            "QR-код ученика и перейдите по нему в аккаунте ребёнка."
        ),
        "access_revoked": (
            "Эта привязка отключена. Обратитесь к администратору школы, "
            "чтобы проверить и восстановить доступ."
        ),
        "contact_not_found": (
            "Данные из письма не найдены. Проверьте, что открыли последнее "
            "письмо вашей школы, или попросите отправить новую ссылку."
        ),
        "contact_has_no_students": (
            "В данных из письма пока нет учеников. Попросите школу проверить "
            "связь родителя с детьми."
        ),
        "too_many_attempts": (
            "Слишком много попыток подряд. Подождите несколько минут и повторите вход."
        ),
    }
    if exc.error_code in messages:
        return messages[exc.error_code]
    if exc.status_code == 429:
        return messages["too_many_attempts"]
    detail = (exc.detail or str(exc)).casefold()
    if "сначала должен подключиться родитель" in detail:
        return messages["parent_link_inactive"]
    if "уже привязан" in detail or "уже связан" in detail:
        return messages["student_already_bound"]
    if exc.status_code == 404:
        return messages["contact_not_found"]
    if exc.status_code == 409:
        return messages["account_role_conflict"]
    if exc.status_code in {400, 410, 422}:
        return messages["invitation_invalid"]
    if exc.status_code in {401, 403}:
        return (
            "Не удалось подтвердить право на вход. Откройте приложение заново "
            "через бота. Если это не поможет, сообщите о проблеме в разделе "
            "помощи."
        )
    return (
        "Сейчас не удалось связаться со школой. Повторите попытку немного "
        "позже. Если проблема останется, нажмите «Сообщить о проблеме»."
    )
